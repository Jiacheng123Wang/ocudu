#!/usr/bin/env python3
"""Score a trained depth-3 model against the baseline that decides whether it is worth anything.

Three receivers, the same samples, the same decoder:

* **the network**, from the frozen contract's input plane;
* **a classical receiver with GENIE channel knowledge**: the true channel, zero-forcing
  equalization and a max-log soft demapper of the same constellation, followed by the same
  inverse chain. Removing channel estimation from the comparison is the point: it asks whether the
  network's LLRs beat a receiver that already knows the channel. That is `design` section 2.5's
  ablation 4, the upper bound of this structure;
* **perfect LLRs**, which must decode with zero block errors and exists to keep the metric honest.

`design` section 2.5's ablation 3 (the classical channel estimate instead of the true one) is the
other half of the picture and belongs with the refiner arm; this script covers the stronger
reference first, because a model that does not beat genie channel knowledge has nothing to explain.

Both learned and classical receivers run through `ldpc_decode`, so the comparison is between LLRs
rather than between decoders. It is not a substitute for the chain: the acceptance criterion stays
the chain's own LDPC decoder and CRC.

Usage
-----
    eval_depth3.py --model <run dir>/depth3_best.keras --data <npz> [--samples 96]
"""

import argparse
import os
import sys
from collections import defaultdict

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import depth3 as D3                # noqa: E402
import ldpc_decode as LD           # noqa: E402
import train_depth3 as T           # noqa: E402


def constellation(qm):
    """Every constellation point with its bit label, generated BY the modulator itself.

    Returns `(points, labels)` with `labels[i, bit]` the value of bit `bit` at point `i`.

    The labels come from `dd_label.modulate` rather than from a re-derivation of the mapping. The
    first version of this function assumed a plain binary-reflected labeling and got a baseline
    whose uncoded error rate was 0.56, i.e. worse than guessing: a receiver with perfect channel
    knowledge cannot be worse than chance unless the comparison itself is wrong.
    """
    import dd_label as DL
    count = 1 << qm
    labels = ((np.arange(count)[:, None] >> np.arange(qm - 1, -1, -1)[None, :]) & 1).astype(np.uint8)
    # `modulate` consumes a flat bit sequence, qm bits per symbol, in label order.
    points = np.asarray(DL.modulate(labels.reshape(-1).tolist(), qm))
    return points, labels


def max_log_llr(symbols, noise_variances, qm):
    """Max-log LLRs, positive meaning bit 0, `qm` per resource element.

    `noise_variances` is per resource element, because a zero-forcing equalizer colours the noise
    through the channel it divides by, and using one average would flatter the baseline.
    """
    points, bit_of_point = constellation(qm)

    symbols = np.asarray(symbols).reshape(-1)
    noise = np.maximum(np.asarray(noise_variances, dtype=np.float64).reshape(-1), 1e-12)
    distance = np.abs(symbols[:, None] - points[None, :]) ** 2 / noise[:, None]
    llr = np.empty((symbols.size, qm), dtype=np.float64)
    for bit in range(qm):
        zero = distance[:, bit_of_point[:, bit] == 0].min(axis=1)
        one = distance[:, bit_of_point[:, bit] == 1].min(axis=1)
        llr[:, bit] = one - zero
    return llr.reshape(-1)


def genie_llr(plane, channel, sigma2_over_r2, alloc, dmrs_symbols, modulation):
    """Zero-forcing LLRs from the true channel, in the chain's codeword order.

    `channel` is `[subcarrier, symbol]` complex and already divided by the reference amplitude,
    which is the same normalisation the contract's plane uses, so the two are consistent without
    restoring physical units.
    """
    # The contract's plane is [subcarrier, 1, channel]; `unpack_input` reads [subcarrier, channel].
    plane = np.asarray(plane)
    if plane.ndim == 3:
        plane = plane[:, 0, :]
    back = D3.unpack_input(plane, alloc, dmrs_symbols, 1)
    grid = back["grid"]                                   # [symbol, subcarrier]
    subcarriers, symbols = D3.data_re_indices(alloc, dmrs_symbols)
    received = grid[symbols, subcarriers]
    estimate = channel[subcarriers, symbols]
    equalized = received / estimate
    noise = sigma2_over_r2 / (np.abs(estimate) ** 2)
    return max_log_llr(equalized, noise, D3.BITS_PER_SYMBOL[modulation])


def perfect_llr(sample):
    """The LLRs a perfect model emits: the label is `1 - b` and positive means bit 0."""
    return (2.0 * sample["llr_shape"] - 1.0) * LD.KNOWN_LLR


def evaluate(args):
    import tensorflow as tf
    tf.get_logger().setLevel("ERROR")

    data = T.Batches(args.data, args.modulation, max_samples=args.samples, seed=args.seed)
    model = tf.keras.models.load_model(args.model, compile=False,
                                       custom_objects={"FoldedScaleConv": T.FoldedScaleConv})
    scale = D3.RANGE_LIMIT_FLOAT[args.modulation]

    receivers = {name: T.CodedBler(data) for name in ("network", "genie", "perfect")}
    bit_errors = defaultdict(int)
    bit_total = defaultdict(int)

    for index in range(data.n):
        sample = data.sample(index)
        alloc = data.allocation_of(index)
        dmrs_symbols = data.dmrs_symbols_of(index)
        modulation = data.modulation_of(index)

        outputs = model(tf.constant(sample["x"][None, ...]), training=False)
        network = D3.llr_gather(np.asarray(outputs["llr"])[0, :, 0, :] * scale, alloc, dmrs_symbols,
                                modulation)
        channel = sample["ch"][:, :, 0] + 1j * sample["ch"][:, :, 1]
        genie = genie_llr(sample["x"], channel, sample["sigma2_over_r2"], alloc, dmrs_symbols,
                          modulation)
        perfect = D3.llr_gather(perfect_llr(sample), alloc, dmrs_symbols, modulation)

        labels = D3.llr_gather(sample["llr_shape"], alloc, dmrs_symbols, modulation)
        valid = D3.llr_gather((sample["llr_weights"] > 0).astype(np.float32), alloc, dmrs_symbols,
                              modulation) > 0
        bit_total["all"] += int(valid.sum())
        for name, llr in (("network", network), ("genie", genie), ("perfect", perfect)):
            receivers[name].add(index, llr)
            bit_errors[name] += int(((llr[valid] > 0) != (labels[valid] > 0.5)).sum())

    print(f"{args.model}\n  on {data.n} samples of {os.path.basename(args.data)}")
    print(f"  {'receiver':10s} {'uncoded BER':>12s} {'coded BLER':>11s} {'blocks':>8s} "
          f"{'skipped':>8s}")
    for name in ("network", "genie", "perfect"):
        counter = receivers[name]
        ber = bit_errors[name] / max(bit_total["all"], 1)
        bler = counter.rate()
        print(f"  {name:10s} {ber:12.4f} {bler:11.4f} {counter.blocks:8d} {counter.skipped:8d}")

    assert receivers["perfect"].errors == 0, (
        "perfect LLRs did not decode cleanly, so the comparison below them is not trustworthy")
    if receivers["genie"].errors == 0:
        print("  note: the genie receiver decoded every block, so the coded comparison is at its "
              "ceiling and the uncoded column is the informative one")
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--model", required=True)
    parser.add_argument("--data", required=True)
    parser.add_argument("--modulation", default="256QAM")
    parser.add_argument("--samples", type=int, default=96)
    parser.add_argument("--seed", type=int, default=20261013)
    args = parser.parse_args()
    return evaluate(args)


if __name__ == "__main__":
    raise SystemExit(main())
